#!/bin/bash
# === 第03章：Angular 介紹 - Node.js & npm 常用指令 ===
#
# 這個檔案列出 Node.js 和 npm 的常用指令，供你查閱使用。
# 不需要直接執行這個檔案，把指令複製到終端機輸入即可。

# ============================================================
# 確認安裝版本
# ============================================================

# 查看 Node.js 版本
node -v
# 預期輸出範例：v20.11.0

# 查看 npm 版本
npm -v
# 預期輸出範例：10.2.4

# ============================================================
# npm 常用指令
# ============================================================

# 查看某個套件的相關資訊
npm info @angular/core

# 安裝專案所有依賴套件（在有 package.json 的資料夾裡執行）
# 就像「把購物清單上的東西全部買回來」
npm install

# 安裝特定套件（以 lodash 為例）
# --save 代表這個套件是正式需要的（會記錄到 package.json）
npm install lodash --save

# 安裝開發用套件（只在開發時用，不會跟著專案一起發布）
npm install prettier --save-dev

# 移除某個套件
npm uninstall lodash

# 查看全域安裝的套件清單
npm list -g --depth=0
